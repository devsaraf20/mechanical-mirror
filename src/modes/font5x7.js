export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch) {
  return G[ch] || G[ch.toUpperCase()] || G['?'];
}

/**
 * Render a string to an array of column bitmasks (bit 0 = top), with one
 * blank column between glyphs.
 */
export function textColumns(text) {
  const cols = [];
  for (const ch of text) {
    cols.push(...glyph(ch), 0);
  }
  return cols;
}
